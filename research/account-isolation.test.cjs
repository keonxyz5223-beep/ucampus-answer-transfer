const assert = require('node:assert/strict');
const { accountRecord, accountFromHomeFields, accountFromHomeState, accountFromPlayer } = require('../ucampus-answer-transfer.user.js');
const first = accountFromHomeFields('甲大学', '学号：2026000001', { code: '2026000001', userId: 71, schId: 12 });
const second = accountFromHomeFields('甲大学', '学号：2026000002', { code: '2026000002', userId: 72, schId: 12 });
const otherSchool = accountFromHomeFields('乙大学', '学号：2026000001');
assert.ok(first && second && otherSchool);
assert.equal(accountFromHomeState({ schName: '甲大学', code: '2026000001', userId: 71, schId: 12 }).key, first.key, '首页下拉菜单隐藏时仍读取登录状态');
assert.equal(accountFromHomeState({ schName: '甲大学', code: '2026000001' }), null, '未登录状态不能归属提交记录');
assert.notEqual(first.key, second.key, '同校不同学号不能共用记录');
assert.notEqual(first.key, otherSchool.key, '不同学校同学号不能共用记录');
assert.equal(accountFromHomeFields('甲大学', '教师 · 工号：2026000001'), null);
assert.equal(accountFromHomeFields('甲大学', '学号：2026000001', { code: '2026000002' }), null);
assert.equal(accountFromPlayer({ user_id: 71, code: '2026000001', schName: '甲大学' }, second).key, first.key);
assert.equal(accountFromPlayer({ user_id: 71, code: '2026000001', school: 12 }, first).key, first.key);
assert.equal(accountFromPlayer({ code: 200, rt: { user_id: 71, school: 12 } }, first).key, first.key, '接口包装了 rt 时沿用已核对的首页身份');
assert.equal(accountFromPlayer({ code: 200, rt: { user_id: 72, code: '2026000002', schName: '甲大学' } }, first).key, second.key, '接口返回另一个人时分开标记');
assert.notEqual(accountFromPlayer({ user_id: 72, code: '2026000001', school: 12 }, first).key, first.key, '身份编号冲突时要另建记录区');
assert.equal(accountFromPlayer({ user_id: 72, code: '2026000002', school: 12 }, first).key, second.key, '同校另一学号应使用自己的记录区');
assert.notEqual(accountFromPlayer({ code: '2026000001', school: 15, user_id: 88 }, first).key, first.key, '异校同学号必须使用另一记录区');
assert.notEqual(accountFromPlayer({ user_id: 'another-88' }, first).key, first.key, '学号缺失时只用独立账号编号隔离');
assert.equal(accountFromPlayer({ code: '2026000001' }, first), null, '只凭学号不能猜测学校');
assert.equal(accountRecord('', '2026000001'), null);
console.log('账号标识隔离与跨页身份校验通过。');
